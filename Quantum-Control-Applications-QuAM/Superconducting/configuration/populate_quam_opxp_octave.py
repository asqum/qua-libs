# %%
# Change active qubits
machine.active_qubit_names = ["q1", "q2"]  # change

for i, qubit in enumerate(machine.qubits.values()):
    qubit.grid_location = f"{i},0"

rr_qubits = {name: q for name, q in machine.qubits.items() if q.resonator is not None}
z_qubits = {name: q for name, q in machine.qubits.items() if q.z is not None}

# %%                                 Resonator parameters
########################################################################################################################
# Be mindful that the Octave LO synthesizers are shared between ports:
#   synth1: RF1 and RFin1
#   synth2: RF2 and RF3
#   synth3: RF4 and RF5
# Octave LO frequency [2 : 0.250 : 18] GHz
# Octave gain [-20 : 0.5 : 20] dB
# Resonators sharing the same RF output also share the same LO.

rr_freq = {"q1": 5.932987219 * u.GHz}  # change
rr_LO = 6.0 * u.GHz  # change
rr_if = {name: f - rr_LO for name, f in rr_freq.items()}
assert all(abs(f_if) < 400 * u.MHz for f_if in rr_if.values()), (
    "The resonator intermediate frequency must be within [-400; 400] MHz. \n"
    f"Readout frequencies: {rr_freq} \n"
    f"Readout LO frequency: {rr_LO} \n"
    f"Readout IF frequencies: {rr_if} \n"
)

# Desired output power in dBm
readout_power = -40  # change
rr_gain, rr_amplitude = get_octave_gain_and_amplitude(readout_power, max_amplitude=0.125 / len(rr_qubits))

for name, qubit in rr_qubits.items():
    qubit.resonator.f_01 = rr_freq[name]
    qubit.resonator.intermediate_frequency = int(rr_if[name])
    qubit.resonator.frequency_converter_up.LO_frequency = rr_LO
    qubit.resonator.frequency_converter_up.gain = rr_gain
    qubit.resonator.frequency_converter_up.output_mode = "always_on"  # "always_on" or "triggered"
    qubit.resonator.frequency_converter_down.LO_frequency = rr_LO  # must match the up-converter LO (synth1)

# %%                                 Qubit drive parameters
########################################################################################################################
xy_freq = {"q1": 5.1086041109 * u.GHz, "q2": 4.8342292556 * u.GHz}  # change
xy_LO = {"q1": 5.25 * u.GHz, "q2": 5.0 * u.GHz}  # change
xy_if = {name: xy_freq[name] - xy_LO[name] for name in xy_freq}
assert all(abs(f_if) < 400 * u.MHz for f_if in xy_if.values()), (
    "The xy intermediate frequency must be within [-400; 400] MHz. \n"
    f"Qubit drive frequencies: {xy_freq} \n"
    f"Qubit drive LO frequencies: {xy_LO} \n"
    f"Qubit drive IF frequencies: {xy_if} \n"
)
anharmonicity = {"q1": -200 * u.MHz, "q2": -200 * u.MHz}  # change

# Desired output power in dBm
drive_power = -10  # change
xy_gain, xy_amplitude = get_octave_gain_and_amplitude(drive_power)

for name, qubit in machine.qubits.items():
    qubit.f_01 = xy_freq[name]
    qubit.anharmonicity = anharmonicity[name]
    qubit.xy.intermediate_frequency = int(xy_if[name])
    qubit.xy.frequency_converter_up.LO_frequency = xy_LO[name]
    qubit.xy.frequency_converter_up.gain = xy_gain
    qubit.xy.frequency_converter_up.output_mode = "always_on"  # "always_on" or "triggered"

# %%                                 Pulse parameters
########################################################################################################################
for qubit in rr_qubits.values():
    # Readout
    qubit.resonator.operations["readout"].length = 2 * u.us  # change
    qubit.resonator.operations["readout"].amplitude = rr_amplitude

for qubit in machine.qubits.values():
    xy = qubit.xy
    # Qubit saturation
    xy.operations["saturation"].length = 20 * u.us  # change
    xy.operations["saturation"].amplitude = 0.3
    # Single qubit gates - DragCosine
    xy.operations["x180_DragCosine"].length = 40  # change
    xy.operations["x180_DragCosine"].amplitude = xy_amplitude
    xy.operations["x90_DragCosine"].amplitude = xy.operations["x180_DragCosine"].amplitude / 2
    # Single qubit gates - Square
    xy.operations["x180_Square"].length = 40  # change
    xy.operations["x180_Square"].amplitude = xy_amplitude
    xy.operations["x90_Square"].amplitude = xy.operations["x180_Square"].amplitude / 2

# %%                                 Flux parameters
########################################################################################################################
# OPX+ analog outputs are limited to [-0.5, 0.5) V
for qubit in z_qubits.values():
    qubit.z.operations["const"].amplitude = 0.1
    # set joint_offset and min_offset the same as the independent_offset # for AS
    qubit.z.independent_offset = 0.0
    qubit.z.joint_offset = "#./independent_offset"
    qubit.z.min_offset = "#./independent_offset"

for qp in machine.qubit_pairs.values():
    qp.coupler.operations["const"].amplitude = 0.1
    qp.extras["T1"] = 30e-6
    qp.extras["T2"] = 5e-6

# %%
# save into state.json
save_machine(machine, path)

# %%
# View the corresponding "raw-QUA" config
with open("qua_config.json", "w+") as f:
    json.dump(machine.generate_config(), f, indent=4)

