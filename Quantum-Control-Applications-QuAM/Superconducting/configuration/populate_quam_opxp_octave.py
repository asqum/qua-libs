"""
Populate a QuAM state generated by make_wiring_opxp_octave.py + make_quam.py (OPX+ & Octave)
with initial values based on previous calibrations or chip specs.

For OPX1000 (LF-FEM & MW-FEM) use populate_quam_lf_mw_fems.py instead.
"""
import json
from qualang_tools.units import unit
from quam_libs.components import QuAM
from quam_libs.quam_builder.machine import save_machine
import numpy as np

path = "C:/Users/JackChao/OneDrive - QM Machines LTD/Customer/windows/AS/qua-libs/Quantum-Control-Applications-QuAM/Superconducting/configuration/quam_state/test"
machine = QuAM.load(path)

# %%                                 QUAM loading and auxiliary functions
########################################################################################################################
# Class containing tools to help handling units and conversions.
u = unit(coerce_to_integer=True)


def get_octave_gain_and_amplitude(desired_power: float, max_amplitude: float = 0.125) -> tuple[float, float]:
    """Get the Octave gain and IF amplitude for the Octave to output the specified desired power.

    Args:
        desired_power: Desired output power in dBm.
        max_amplitude: Maximum allowed IF amplitude provided by the OPX to the Octave in V.
            Default is 0.125 V, which is the optimum for driving the Octave up-conversion mixers.

    Returns:
        The Octave gain [dB] and IF amplitude [V] realizing the desired power.
    """
    resulting_power = desired_power - u.volts2dBm(max_amplitude)
    if resulting_power < 0:
        octave_gain = round(max(desired_power - u.volts2dBm(max_amplitude) + 0.5, -20) * 2) / 2
    else:
        octave_gain = round(min(desired_power - u.volts2dBm(max_amplitude) + 0.5, 20) * 2) / 2
    amplitude = u.dBm2volts(desired_power - octave_gain)

    if -20 <= octave_gain <= 20 and -0.5 <= amplitude < 0.5:
        return octave_gain, amplitude
    raise ValueError(
        f"The desired power is outside the specifications ([-20; +20]dB, [-0.5; +0.5)V), got ({octave_gain}; {amplitude})"
    )


